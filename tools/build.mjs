write('data/ids.json', json(registry));
write('data/cases.json', json({ schemaVersion: 1, cases }));
const index = cases.map(({ id, title, category, relatedCategories, organization, summary, motion, paths }) => ({ id, title, category, relatedCategories, organization, summary, motionTags: motion.tags, paths }));
